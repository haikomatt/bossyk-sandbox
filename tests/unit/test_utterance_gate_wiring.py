@pytest.mark.parametrize("history", [[], [ProposedAction("get_thing", {})]])
def test_always_block_fake_ignores_history_shape(history: Any) -> None:
    # Sanity check on the fake itself: it must accept whatever history shape
    # agent_node passes (this repo's convention: don't over-fit a fake to
    # one call site).
    rule = _AlwaysBlockUtterance()

    decision = rule.score("anything", history)

    assert decision.verdict is Verdict.BLOCK
